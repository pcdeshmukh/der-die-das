const STRINGS = { en, de, es };

/** Translate a UI string. Reading the store here makes components re-render on language change. */
export function t(key: StringKey, vars?: Record<string, string | number>): string {
  let s: string = STRINGS[progress.value.settings.uiLang][key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

export const uiLang = () => progress.value.settings.uiLang;

/** The learner-language meaning of a word, sentence, verb or exercise. */
export const meaning = (x: Translated) => x[progress.value.settings.hintLang] ?? x.en;
